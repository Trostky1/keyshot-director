// Renders docs/LIGHTING_CAPABILITY_RECORD.md from server/lighting-capabilities.js.
//   node tools/render_capability_record.js          write the file
//   node tools/render_capability_record.js --check  exit 1 if the file is out of date
const fs = require('fs'), path = require('path');
const { EVIDENCE, RECORD } = require('../server/lighting-capabilities');

const cell = s => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
function table(headers, rows) {
  return [`| ${headers.join(' | ')} |`, `|${headers.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}
function render() {
  const out = [];
  out.push('# Lighting capability and evidence record', '',
    '<!-- Generated by tools/render_capability_record.js from server/lighting-capabilities.js. Edit the data module, then regenerate. -->', '',
    `Record version ${RECORD.record_version}, recorded ${RECORD.recorded}. Inspected base: ${RECORD.inspected_base}.`, '',
    RECORD.scope, '',
    `**Authority.** ${RECORD.supersedes.join(' ')} [Measured refinement](MEASURED_REFINEMENT.md) and the code are the authority for the acceptance loop. Nothing here is a similarity percentage or a claim of arbitrary 1:1 photograph matching.`, '',
    '## Evidence labels', '', table(['Label', 'Meaning'], Object.entries(EVIDENCE).map(([k, v]) => [`\`${k}\``, v])), '');
  out.push('## Light source families', '');
  for (const family of RECORD.sources) {
    out.push(`### ${family.name}`, '', `In the photo plan grammar: **${family.in_photo_grammar ? 'yes' : 'no'}**.`, '',
      table(['Id', 'Capability', 'Evidence', 'Where', 'Basis'], family.parameters.map(p => [`\`${p.id}\``, p.name, `\`${p.evidence}\``, p.where, p.basis])), '');
  }
  const section = (title, items) => out.push(`## ${title}`, '', table(['Id', 'Capability', 'Evidence', 'Where', 'Basis'], items.map(p => [`\`${p.id}\``, p.name, `\`${p.evidence}\``, p.where, p.basis])), '');
  section('Environment', RECORD.environment);
  section('Controls added or clarified in this record', RECORD.controls);
  section('Recovery and ownership', RECORD.recovery);
  section('Measurement and comparison', RECORD.measurement);
  section('Search and reconstruction', RECORD.search);
  out.push('## Research experiments', '', 'Offline results never close an experiment. Each stays open until the live column says otherwise.', '',
    table(['Id', 'Question', 'Offline coverage', 'Live KeyShot status'], RECORD.experiments.map(e => [`**${e.id}**`, e.question, e.offline, e.live])), '');
  return out.join('\n');
}
const target = path.join(__dirname, '..', 'docs', 'LIGHTING_CAPABILITY_RECORD.md');
if (require.main === module) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) { console.error('docs/LIGHTING_CAPABILITY_RECORD.md is out of date; run node tools/render_capability_record.js'); process.exit(1); }
  } else fs.writeFileSync(target, text);
}
module.exports = { render, target };
